/**
 * Pre-build script: generates src/content/blog/index.ts
 * with frontmatter for all blog posts (no fs reads at runtime).
 * Run: npx tsx scripts/build-blog-index.ts
 */
import fs from 'fs';
import path from 'path';
import matter from 'gray-matter';

const BLOG_DIR = path.join(process.cwd(), 'src/content/blog');
const OUTPUT = path.join(process.cwd(), 'src/content/blog/index.ts');

interface PostMeta {
  title: string;
  description: string;
  slug: string;
  date: string;
  updated?: string;
  author: string;
  readingTime: number;
  tags: string[];
  keywords: string[];
  faq?: { q: string; a: string }[];
  related?: string[];
}

function calculateReadingTime(content: string): number {
  const words = content.trim().split(/\s+/).length;
  return Math.max(1, Math.ceil(words / 200));
}

const sites = ['general', 'tutors', 'creative'];
const index: Record<string, PostMeta[]> = {};

for (const site of sites) {
  const dir = path.join(BLOG_DIR, site);
  if (!fs.existsSync(dir)) {
    index[site] = [];
    continue;
  }

  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.mdx'));
  const posts: PostMeta[] = [];

  for (const file of files) {
    try {
      const raw = fs.readFileSync(path.join(dir, file), 'utf-8');
      const { data, content } = matter(raw);
      posts.push({
        title: data.title,
        description: data.description,
        slug: data.slug,
        date: data.date,
        updated: data.updated,
        author: data.author || 'Grzegorz Stępień',
        readingTime: data.readingTime ?? calculateReadingTime(content),
        tags: data.tags || [],
        keywords: data.keywords || [],
        faq: data.faq,
        related: data.related,
      });
    } catch (err) {
      console.error(`[build-blog-index] Error parsing ${site}/${file}:`, err);
    }
  }

  posts.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
  index[site] = posts;
}

const output = `// AUTO-GENERATED by scripts/build-blog-index.ts — do not edit manually
// Run: npx tsx scripts/build-blog-index.ts

export interface BlogPostMeta {
  title: string;
  description: string;
  slug: string;
  date: string;
  updated?: string;
  author: string;
  readingTime: number;
  tags: string[];
  keywords: string[];
  faq?: { q: string; a: string }[];
  related?: string[];
}

export const blogIndex: Record<string, BlogPostMeta[]> = ${JSON.stringify(index, null, 2)};

export function getBlogPostsMeta(site: string): BlogPostMeta[] {
  return blogIndex[site] ?? [];
}
`;

fs.writeFileSync(OUTPUT, output, 'utf-8');

const totalPosts = Object.values(index).reduce((sum, posts) => sum + posts.length, 0);
console.log(`[build-blog-index] Generated ${OUTPUT}`);
for (const [site, posts] of Object.entries(index)) {
  console.log(`  ${site}: ${posts.length} posts`);
}
console.log(`  Total: ${totalPosts} posts`);
